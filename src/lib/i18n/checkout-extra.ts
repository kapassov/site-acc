export const checkoutExtra = { ru, kz, en } satisfies Record<Lang, CheckoutExtraCopy>;

export function checkoutText(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  ));
}

const localeByLanguage: Record<Lang, string> = { ru: "ru-RU", kz: "kk-KZ", en: "en-US" };

export function checkoutNumber(value: number, lang: Lang): string {
  return value.toLocaleString(localeByLanguage[lang]);
}

export function checkoutDistance(distanceKm: number, lang: Lang): string {
  if (distanceKm < 1) {
    const metres = Math.max(10, Math.round(distanceKm * 100) * 10);
    return `${checkoutNumber(metres, lang)} ${lang === "en" ? "m" : "м"}`;
  }
  const value = new Intl.NumberFormat(localeByLanguage[lang], {
    maximumFractionDigits: distanceKm < 10 ? 1 : 0,
  }).format(distanceKm);
  return `${value} ${lang === "en" ? "km" : "км"}`;
}
